-- דורש שטבלת public.customers תהיה קיימת עם עמודת id.
-- customer_id יווצר באותו טיפוס כמו customers.id (uuid או bigint וכו').

-- 1) יצירת טבלה אם עדיין אין (כולל PK תקין)
CREATE TABLE IF NOT EXISTS public.repairs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT repairs_pkey PRIMARY KEY (id)
);

-- 2) אם נוצר בעבר עם שם אילוץ שגוי reapris_pkey — מתקנים
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM pg_constraint c
    JOIN pg_class t ON c.conrelid = t.oid
    JOIN pg_namespace n ON t.relnamespace = n.oid
    WHERE n.nspname = 'public'
      AND t.relname = 'repairs'
      AND c.conname = 'reapris_pkey'
  ) THEN
    ALTER TABLE public.repairs RENAME CONSTRAINT reapris_pkey TO repairs_pkey;
  END IF;
END $$;

-- 3) עמודות פשוטות (בלי FK) — כל אחת בנפרד כדי שלא ייפלו כולן בגלל שורה אחת
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS license_plate text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS vehicle_manufacturer text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS vehicle_model text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS vehicle_year text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS vehicle_color text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS test_validity text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS description text;
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS notes text;

-- status: ברירת מחדל בלי NOT NULL קשיח בשלב הראשון (מונע כשל אם כבר יש שורות)
ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS status text DEFAULT 'open';
UPDATE public.repairs SET status = 'open' WHERE status IS NULL;

DO $$
BEGIN
  ALTER TABLE public.repairs ALTER COLUMN status SET DEFAULT 'open';
EXCEPTION
  WHEN undefined_column THEN NULL;
END $$;

-- 4) customer_id — אותו טיפוס כמו customers.id, ואז FK בנפרד
DO $$
DECLARE
  id_type text;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO id_type
  FROM pg_attribute a
  JOIN pg_class c ON c.oid = a.attrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND c.relname = 'customers'
    AND a.attname = 'id'
    AND a.attnum > 0
    AND NOT a.attisdropped;

  IF id_type IS NULL THEN
    RAISE EXCEPTION 'לא נמצא public.customers.id — צור קודם את טבלת הלקוחות';
  END IF;

  EXECUTE format(
    'ALTER TABLE public.repairs ADD COLUMN IF NOT EXISTS customer_id %I',
    id_type
  );
END $$;

-- FK (אם כבר קיים עם אותו שם — מוחקים ומוסיפים מחדש)
ALTER TABLE public.repairs DROP CONSTRAINT IF EXISTS repairs_customer_id_fkey;

ALTER TABLE public.repairs
  ADD CONSTRAINT repairs_customer_id_fkey
  FOREIGN KEY (customer_id)
  REFERENCES public.customers (id)
  ON DELETE RESTRICT;

COMMENT ON COLUMN public.repairs.status IS 'open | in_progress | done | cancelled';

